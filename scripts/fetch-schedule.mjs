#!/usr/bin/env node
// Fetch a tournament schedule from fixturedownload.com and normalize it into a
// reusable, tournament-agnostic JSON schema. Also emits a .js wrapper that
// assigns the data to a global so the static page works from file:// without a
// server.
//
// Usage:
//   node scripts/fetch-schedule.mjs
//   node scripts/fetch-schedule.mjs --slug fifa-world-cup-2026 --name "FIFA World Cup 2026"
//   node scripts/fetch-schedule.mjs --slug epl-2026 --name "English Premier League 2026-27" --kind league

import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DATA_DIR = join(ROOT, 'data');

function parseArgs(argv) {
  const args = { slug: 'fifa-world-cup-2026', name: 'FIFA World Cup 2026', kind: 'worldcup' };
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--slug') args.slug = argv[++i];
    else if (a === '--name') args.name = argv[++i];
    else if (a === '--kind') args.kind = argv[++i];
  }
  return args;
}

// League season (e.g. Premier League): every round is just a matchday.
function leagueStageFor(roundNumber) {
  return { stage: 'league', round: `Matchday ${roundNumber}` };
}

// Map fixturedownload RoundNumber -> stage id + display label for a 48-team
// World Cup (104 matches). Group matchdays are 1-3; knockouts follow.
function worldCupStageFor(roundNumber, group) {
  if (group) {
    return { stage: 'group', round: `Matchday ${roundNumber}` };
  }
  switch (roundNumber) {
    case 4: return { stage: 'round-of-32', round: 'Round of 32' };
    case 5: return { stage: 'round-of-16', round: 'Round of 16' };
    case 6: return { stage: 'quarter-final', round: 'Quarter-finals' };
    case 7: return { stage: 'semi-final', round: 'Semi-finals' };
    case 8: return { stage: 'final', round: 'Final' };
    case 9: return { stage: 'third-place', round: 'Third-place play-off' };
    default: return { stage: 'knockout', round: `Round ${roundNumber}` };
  }
}

// "2026-06-11 19:00:00Z" -> "2026-06-11T19:00:00Z"
function toIsoUtc(dateUtc) {
  const trimmed = String(dateUtc).trim();
  const normalized = trimmed.replace(' ', 'T');
  const withZ = /[Zz]$/.test(normalized) ? normalized : `${normalized}Z`;
  const d = new Date(withZ);
  if (Number.isNaN(d.getTime())) {
    throw new Error(`Unparseable DateUtc: ${dateUtc}`);
  }
  return d.toISOString().replace('.000', '');
}

const TBD = new Set(['To be announced', 'TBD', '']);
function team(name) {
  if (name == null || TBD.has(String(name).trim())) return null;
  return String(name).trim();
}

function normalize(raw, { slug, name, kind }) {
  const matches = raw
    .map((m) => {
      const group = m.Group ? String(m.Group).trim() : null;
      const { stage, round } = kind === 'league'
        ? leagueStageFor(m.RoundNumber)
        : worldCupStageFor(m.RoundNumber, group);
      return {
        id: m.MatchNumber,
        stage,
        round,
        group: group || null,
        kickoffUtc: toIsoUtc(m.DateUtc),
        venue: m.Location ? String(m.Location).trim() : null,
        home: team(m.HomeTeam),
        away: team(m.AwayTeam),
      };
    })
    .sort((a, b) => a.kickoffUtc.localeCompare(b.kickoffUtc) || a.id - b.id);

  return {
    id: slug,
    name,
    source: `https://fixturedownload.com/feed/json/${slug}`,
    fetchedAt: new Date().toISOString(),
    matches,
  };
}

async function main() {
  const { slug, name, kind } = parseArgs(process.argv.slice(2));
  const url = `https://fixturedownload.com/feed/json/${slug}`;
  process.stdout.write(`Fetching ${url} ...\n`);

  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Request failed: ${res.status} ${res.statusText}`);
  }
  const raw = await res.json();
  if (!Array.isArray(raw) || raw.length === 0) {
    throw new Error('Unexpected feed format: expected a non-empty array');
  }

  const data = normalize(raw, { slug, name, kind });

  await mkdir(DATA_DIR, { recursive: true });
  const jsonPath = join(DATA_DIR, `${slug}.json`);
  const jsPath = join(DATA_DIR, `${slug}.js`);

  const json = JSON.stringify(data, null, 2);
  await writeFile(jsonPath, `${json}\n`, 'utf8');

  const jsBanner = '// Auto-generated by scripts/fetch-schedule.mjs. Do not edit by hand.\n';
  const js =
    `${jsBanner}window.SCHEDULES = window.SCHEDULES || {};\n` +
    `window.SCHEDULES[${JSON.stringify(slug)}] = ${json};\n`;
  await writeFile(jsPath, js, 'utf8');

  process.stdout.write(
    `Wrote ${data.matches.length} matches\n  ${jsonPath}\n  ${jsPath}\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`Error: ${err.message}\n`);
  process.exit(1);
});
